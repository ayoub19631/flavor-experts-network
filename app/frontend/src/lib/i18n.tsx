const I18nContext = createContext<I18nContextType | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(() => {
    const saved = localStorage.getItem("fen-lang");
    return isLanguage(saved) ? saved : "en";
  });

  const setLang = useCallback((newLang: Language) => {
    setLangState(newLang);
    localStorage.setItem("fen-lang", newLang);
  }, []);

  const t = useCallback(
    (key: string): string => {
      const extra = extraTranslations[lang]?.[key];
      if (extra) return extra;
      if (lang === "ar") return translations.ar[key] || translations.en[key] || key;
      return translations.en[key] || key;
    },
    [lang]
  );

  const dir = languageMeta(lang).dir;

  useEffect(() => {
    document.documentElement.setAttribute("dir", dir);
    document.documentElement.setAttribute("lang", lang);
  }, [dir, lang]);

  return (
    <I18nContext.Provider value={{ lang, setLang, t, dir }}>
      {children}
    </I18nContext.Provider>
  );
}

const defaultI18n: I18nContextType = {
  lang: "en",
  setLang: () => {},
  t: (key: string) => translations.en[key] || key,
  dir: "ltr",
};

export function useI18n() {
  const context = useContext(I18nContext);
  return context ?? defaultI18n;
}